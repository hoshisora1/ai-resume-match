def main() -> int:
    parser = argparse.ArgumentParser(description="Build the synthetic live Agent eval dataset")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).with_name("cases.jsonl"),
    )
    args = parser.parse_args()
    rendered = "\n".join(
        json.dumps(case, ensure_ascii=False, separators=(",", ":"))
        for case in build_cases()
    ) + "\n"
    args.output.write_text(rendered, encoding="utf-8", newline="\n")
    version, cases, digest = load_agent_eval_cases(args.output)
    print(
        f"wrote {len(cases)} {version} cases to {args.output} "
        f"(sha256={digest})"
    )
    return 0



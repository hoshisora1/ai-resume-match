def _case(
    *,
    case_id: str,
    task_id: int,
    tags: list[str],
    resume: str,
    title: str,
    job: str,
    skills: list[str],
    minimum: int = 0,
    maximum: int = 100,
    required: list[str] | None = None,
    forbidden: list[str] | None = None,
    no_positive_claims: bool = False,
) -> dict[str, Any]:
    return {
        "datasetVersion": DATASET_VERSION,
        "id": case_id,
        "tags": tags,
        "request": {
            "taskId": task_id,
            "resumeText": resume,
            "jobTitle": title,
            "jobDescription": job,
            "skillTags": skills,
        },
        "expectations": {
            "minScore": minimum,
            "maxScore": maximum,
            "requiredTerms": required or [],
            "forbiddenTerms": forbidden or [],
            "expectNoPositiveClaims": no_positive_claims,
            "maxSteps": 6,
            "maxLatencyMs": 60_000,
        },
    }


